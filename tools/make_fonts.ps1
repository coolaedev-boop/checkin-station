# Builds the Lexend fonts the UI uses into LVGL C fonts (src/ui/fonts/).
#
#   powershell -ExecutionPolicy Bypass -File tools\make_fonts.ps1
#
# Needs Node.js (for npx). Downloads Lexend (SIL Open Font License, via Fontsource)
# and LVGL's FontAwesome symbol font into tools\.cache the first time.
# Body fonts also get the LVGL symbols the UI and keyboard use (LV_SYMBOL_OK, ...),
# so the same label can mix text and symbols.
$ErrorActionPreference = 'Stop'
$root  = Split-Path $PSScriptRoot -Parent
$cache = Join-Path $PSScriptRoot '.cache\fonts'
$out   = Join-Path $root 'src\ui\fonts'
New-Item -ItemType Directory -Force $cache, $out | Out-Null

$sources = @{
  'Lexend-300.ttf'    = 'https://cdn.jsdelivr.net/fontsource/fonts/lexend@latest/latin-300-normal.ttf'
  'Lexend-500.ttf'    = 'https://cdn.jsdelivr.net/fontsource/fonts/lexend@latest/latin-500-normal.ttf'
  'Lexend-700.ttf'    = 'https://cdn.jsdelivr.net/fontsource/fonts/lexend@latest/latin-700-normal.ttf'
  'FontAwesome5.woff' = 'https://raw.githubusercontent.com/lvgl/lvgl/v9.2.2/scripts/built_in_font/FontAwesome5-Solid%2BBrands%2BRegular.woff'
}
foreach ($f in $sources.Keys) {
  $path = Join-Path $cache $f
  if (-not (Test-Path $path)) { Invoke-WebRequest -UseBasicParsing $sources[$f] -OutFile $path }
}

$text    = '0x20-0x7E,0xA0-0xFF,0x2013,0x2019,0x201C,0x201D,0x2022,0x2026'   # ASCII, accents (names), dashes, quotes, bullet, ellipsis
$digits  = '0x20-0x7E,0x2026'
# OK CLOSE LEFT RIGHT WARNING BACKSPACE KEYBOARD NEW_LINE DOWN UP EYE_OPEN EYE_CLOSE
$symbols = '0xF00C,0xF00D,0xF053,0xF054,0xF071,0xF55A,0xF11C,0xF8A2,0xF078,0xF077,0xF06E,0xF070'

#          name               weight size  ranges   symbols?
$fonts = @(
  @('lexend_light_11',  300, 11, $text,   $true),
  @('lexend_light_13',  300, 13, $text,   $true),    # LV_FONT_DEFAULT
  @('lexend_light_14',  300, 14, $text,   $false),
  @('lexend_light_16',  300, 16, $text,   $true),    # keyboard, item name
  @('lexend_light_20',  300, 20, $text,   $true),
  @('lexend_light_24',  300, 24, $text,   $false),
  @('lexend_medium_11', 500, 11, $text,   $false),
  @('lexend_medium_13', 500, 13, $text,   $false),
  @('lexend_bold_18',   700, 18, $digits, $true),    # PIN keypad (uses BACKSPACE)
  @('lexend_bold_32',   700, 32, $digits, $false)
)

$decls = @()
foreach ($f in $fonts) {
  $name, $weight, $size, $ranges, $withSymbols = $f
  $convArgs = @('--yes', 'lv_font_conv@1.5.3', '--bpp', '4', '--size', "$size", '--format', 'lvgl', '--no-compress',
            '--lv-include', 'lvgl.h', '--lv-font-name', $name,
            '--font', (Join-Path $cache "Lexend-$weight.ttf"), '-r', $ranges)
  if ($withSymbols) { $convArgs += @('--font', (Join-Path $cache 'FontAwesome5.woff'), '-r', $symbols) }
  $convArgs += @('-o', (Join-Path $out "$name.c"))
  & npx @convArgs
  if ($LASTEXITCODE -ne 0) { throw "lv_font_conv failed for $name" }
  $file = Join-Path $out "$name.c"                     # keep this machine's paths out of the header comment
  $c = [IO.File]::ReadAllText($file).Replace("$root\", '')
  [IO.File]::WriteAllText($file, $c, (New-Object Text.UTF8Encoding $false))
  $decls += "LV_FONT_DECLARE($name);"
  "  $name"
}

$header = @"
#pragma once
// Generated by tools/make_fonts.ps1. Don't edit; change the list in that script and run it.
#include <lvgl.h>

$($decls -join "`n")
"@
[IO.File]::WriteAllText((Join-Path $out 'Fonts.h'), $header.Replace("`r`n", "`n") + "`n", (New-Object Text.UTF8Encoding $false))
"Wrote $($fonts.Count) fonts to src\ui\fonts"
